const OPCIONAL = /^(assets\/modelos\/|assets\/sonidos\/|assets\/patrones\/|assets\/pegatinas\/ui\/|data\/relieve\/|data\/sismogramas\/|assets\/marca\/velasco)/;
const pedir = (u) => new Request(u, { cache: 'reload' });
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then(async (c) => {
    await c.addAll(PRECARGA.filter((u) => !OPCIONAL.test(u)).map(pedir));
    await Promise.allSettled(PRECARGA.filter((u) => OPCIONAL.test(u)).map((u) => c.add(pedir(u))));
  }).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys()
    .then((ks) => Promise.all(ks.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // APIs externas: directo a la red
  if (req.method === 'HEAD') {
    e.respondWith(caches.match(req, { ignoreMethod: true, ignoreSearch: true })
      .then((r) => (r ? new Response(null, { status: 200, headers: r.headers }) : fetch(req))));
    return;
  }
  if (req.method !== 'GET') return;
  e.respondWith(caches.open(VERSION).then(async (cache) => {
    const guardada = await cache.match(req, { ignoreSearch: true });
    const red = fetch(req).then((r) => {
      if (r.ok && r.type === 'basic') cache.put(req, r.clone());
      return r;
    }).catch(() => null);
    if (guardada) { e.waitUntil(red); return guardada; }
    const r = await red;
    return r || new Response('Sin conexión y sin copia guardada de este archivo.', { status: 503 });
  }));
});
